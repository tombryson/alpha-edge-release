func validAlertScript(script string) bool {
	switch normalizeAlertScript(script) {
	case "cdf", "tms", "etf_tms", "ctf", "q4d", "q3d", "etf_rebalancing":
		return true
	default:
		return false
	}
}

func scriptMatches(script string, candidates ...string) bool {
	normalized := normalizeAlertScript(script)
	for _, candidate := range candidates {
		if normalized == normalizeAlertScript(candidate) {
			return true
		}
	}
	return false
}

