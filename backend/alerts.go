// determineSignalSource implements the architecture's source detection logic
func determineSignalSource(analystPriceTarget, timeframe, signal, ticker, script string) string {
	script = normalizeAlertScript(script)

	// If script is explicitly provided, trust it as authoritative source
	switch script {
	case "etf_tms":
		return "etf_tms"
	case "cdf":
		return "cdf"
	case "tms":
		return "tms"
	case "q4d", "ctf", "q3d":
		return script
	}

	// Fallback heuristics for signals without explicit script field

	// CDF signals have analystPriceTarget field
	if analystPriceTarget != "" {
		return "cdf"
	}

	// TMS add/trim signals have timeframe field
	if timeframe != "" {
		return "tms"
	}

	// TMS event signals
	if signal == "REENTRY" {
		return "tms"
	}

	// CDF zone signals from the TMS script's embedded trend filter.
	if signal == "BREAKOUT" || signal == "SELL_DOWN" {
		return "tms"
	}

	// BUY/SELL without special fields could be:
	// - Regime signal (from SPY, XAO, GOLD, etc.)
	// - ATR stop hit (full exit)
	if signal == "BUY" || signal == "SELL" {
		for _, regimeTicker := range staticdata.KnownRegimeWebhookTickers {
			if ticker == regimeTicker || strings.Contains(ticker, regimeTicker) {
				return "q4d"
			}
		}

		// If SELL signal without analystPriceTarget and not a regime ticker, assume it's a TMS stop hit.
		if signal == "SELL" {
			return "tms"
		}

		// Otherwise unknown/regime
		return "q4d"
	}

	return "unknown"
}

type normalizedWebhookSignal struct {
	AlertType string
	Strength  string
	Timeframe string
	Ignored   bool
	Reason    string
}

func normalizeSignalStrength(value string) string {
	switch strings.ToLower(strings.TrimSpace(value)) {
	case "strong":
		return "Strong"
	case "weak":
		return "Weak"
	default:
		return ""
	}
}

func normalizeSignalTimeframe(value string) string {
	normalized := strings.ToUpper(strings.TrimSpace(value))
	switch normalized {
	case "1D", "2D", "3D":
		return normalized
	default:
		return ""
	}
}

func supportedCanonicalAlertType(value string) string {
	switch canonicalAlertType(value) {
	case "ADD", "TRIM", "BUY", "SELL", "SELL_50", "BREAKOUT", "SELL_DOWN", "REENTRY", "REGIME":
		return canonicalAlertType(value)
	default:
		return ""
	}
}

func normalizeTradingViewSignal(rawSignal, rawStrength, rawSignalStrength, rawTimeframe string) normalizedWebhookSignal {
	signal := strings.ToLower(strings.TrimSpace(rawSignal))
	strength := normalizeSignalStrength(rawStrength)
	if strength == "" {
		strength = normalizeSignalStrength(rawSignalStrength)
	}
	timeframe := normalizeSignalTimeframe(rawTimeframe)

	switch signal {
	case "buy":
		return normalizedWebhookSignal{AlertType: "BUY", Strength: strength, Timeframe: timeframe}
	case "sell":
		return normalizedWebhookSignal{AlertType: "SELL", Strength: strength, Timeframe: timeframe}
	case "strong_add":
		return normalizedWebhookSignal{AlertType: "ADD", Strength: "Strong", Timeframe: timeframe}
	case "weak_add":
		return normalizedWebhookSignal{AlertType: "ADD", Strength: "Weak", Timeframe: timeframe}
	case "strong_trim":
		return normalizedWebhookSignal{AlertType: "TRIM", Strength: "Strong", Timeframe: timeframe}
	case "weak_trim":
		return normalizedWebhookSignal{AlertType: "TRIM", Strength: "Weak", Timeframe: timeframe}
	case "add":
		return normalizedWebhookSignal{AlertType: "ADD", Strength: strength, Timeframe: timeframe}
	case "trim":
		return normalizedWebhookSignal{AlertType: "TRIM", Strength: strength, Timeframe: timeframe}
	case "add_1d":
		return normalizedWebhookSignal{AlertType: "ADD", Strength: strength, Timeframe: "1D"}
	case "add_2d":
		return normalizedWebhookSignal{AlertType: "ADD", Strength: strength, Timeframe: "2D"}
	case "add_3d":
		return normalizedWebhookSignal{AlertType: "ADD", Strength: strength, Timeframe: "3D"}
	case "trim_1d":
		return normalizedWebhookSignal{AlertType: "TRIM", Strength: strength, Timeframe: "1D"}
	case "trim_2d":
		return normalizedWebhookSignal{AlertType: "TRIM", Strength: strength, Timeframe: "2D"}
	case "trim_3d":
		return normalizedWebhookSignal{AlertType: "TRIM", Strength: strength, Timeframe: "3D"}
	case "reentry":
		return normalizedWebhookSignal{AlertType: "REENTRY", Strength: strength, Timeframe: timeframe}
	case "breakout", "cdf_buy_zone":
		return normalizedWebhookSignal{AlertType: "BREAKOUT", Strength: strength, Timeframe: timeframe}
	case "cdf_sell_zone":
		return normalizedWebhookSignal{AlertType: "SELL_DOWN", Strength: strength, Timeframe: timeframe}
	case "price_target_update":
		return normalizedWebhookSignal{}
	case "dca":
		return normalizedWebhookSignal{Ignored: true, Reason: "DCA signal is deprecated"}
	case "oms_buy_zone":
		return normalizedWebhookSignal{Ignored: true, Reason: "legacy buy-zone signal is deprecated"}
	case "oms_sell_zone":
		return normalizedWebhookSignal{Ignored: true, Reason: "legacy sell-zone signal is deprecated"}
	default:
		if canonical := supportedCanonicalAlertType(rawSignal); canonical != "" {
			return normalizedWebhookSignal{AlertType: canonical, Strength: strength, Timeframe: timeframe}
		}
		return normalizedWebhookSignal{Ignored: true, Reason: "unsupported signal"}
	}
}

// handleConnectionSignal registers an active alert in the database
func handleConnectionSignal(w http.ResponseWriter, ticker, script string, allocations map[string]float64) {
	script = normalizeAlertScript(script)

	// Validate script name
	if !validAlertScript(script) {
		log.Printf("[CONNECTION] Invalid script name: %s", script)
		if w != nil {
			http.Error(w, "Invalid script name", http.StatusBadRequest)
		}
		return
	}

	// Insert or update active alert
	_, err := db.Exec(`
		INSERT INTO active_alerts (ticker, script)
		VALUES (?, ?)
		ON CONFLICT(ticker, script) DO UPDATE SET
			created_at = CURRENT_TIMESTAMP
	`, ticker, script)

	if err != nil {
		log.Printf("[CONNECTION] Failed to register alert for %s (%s): %v", ticker, script, err)
		if w != nil {
			http.Error(w, err.Error(), http.StatusInternalServerError)
		}
		return
	}

	// If this is an ETF rebalancing signal with allocations, store them
	if script == "etf_rebalancing" && len(allocations) > 0 {
		// Clear existing allocations
		_, err = db.Exec(`DELETE FROM etf_allocations`)
		if err != nil {
			log.Printf("[ETF] Failed to clear existing allocations: %v", err)
		}

		// Insert new allocations — set both allocation_percent (mutable) and base_weight (immutable strategic weight)
		for etfTicker, allocation := range allocations {
			_, err = db.Exec(`
				INSERT INTO etf_allocations (ticker, allocation_percent, base_weight, last_updated)
				VALUES (?, ?, ?, CURRENT_TIMESTAMP)
				ON CONFLICT(ticker) DO UPDATE SET
					allocation_percent = excluded.allocation_percent,
					base_weight = excluded.base_weight,
					last_updated = CURRENT_TIMESTAMP
			`, etfTicker, allocation, allocation)

			if err != nil {
				log.Printf("[ETF] Failed to store allocation for %s: %v", etfTicker, err)
			}
		}
		log.Printf("[ETF] Stored allocations for %d ETFs", len(allocations))
	}

	log.Printf("[CONNECTION] Registered alert: %s on %s", script, ticker)

	if w != nil {
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(map[string]interface{}{
			"message": "Alert registered",
			"ticker":  ticker,
			"script":  script,
		})
	}
}

// getActiveAlerts returns all registered connection signals
func getActiveAlerts(w http.ResponseWriter, r *http.Request) {
	rows, err := db.Query(`
		SELECT id, ticker, script, created_at
		FROM active_alerts
		ORDER BY created_at DESC
	`)
	if err != nil {
		log.Printf("[API] Failed to query active alerts: %v", err)
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	defer rows.Close()

	type ActiveAlert struct {
		ID        int       `json:"id"`
		Ticker    string    `json:"ticker"`
		Script    string    `json:"script"`
		CreatedAt time.Time `json:"created_at"`
	}

	var activeAlerts []ActiveAlert
	for rows.Next() {
		var alert ActiveAlert
		if err := rows.Scan(&alert.ID, &alert.Ticker, &alert.Script, &alert.CreatedAt); err != nil {
			log.Printf("[API] Failed to scan active alert: %v", err)
			continue
		}
		activeAlerts = append(activeAlerts, alert)
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(activeAlerts)
}

func setupActiveAlert(w http.ResponseWriter, r *http.Request) {
	etfManagementMu.Lock()
	defer etfManagementMu.Unlock()
	var payload struct {
		Ticker             string   `json:"ticker"`
		Script             string   `json:"script"`
		PositionState      string   `json:"position_state"`
		AnalystPriceTarget *float64 `json:"analyst_price_target"`
		CompanyName        string   `json:"company_name"`
	}

	if err := json.NewDecoder(r.Body).Decode(&payload); err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}

	payload.Ticker = strings.TrimSpace(payload.Ticker)
	payload.Script = normalizeAlertScript(payload.Script)
	payload.PositionState = strings.ToUpper(strings.TrimSpace(payload.PositionState))
	payload.CompanyName = strings.TrimSpace(payload.CompanyName)

	if payload.Ticker == "" || !scriptMatches(payload.Script, "cdf", "tms", "etf_tms") {
		http.Error(w, "ticker and valid script are required", http.StatusBadRequest)
		return
	}
	mode, modeErr := etfManagementModeFrom(db, payload.Ticker)
	if modeErr != nil {
		http.Error(w, modeErr.Error(), 500)
		return
	}
	if !etfManagementAccepts(mode, payload.Script) {
		http.Error(w, "This script does not match the fund's selected management mode", http.StatusConflict)
		return
	}
	requiresPositionState := !scriptMatches(payload.Script, "tms")
	if requiresPositionState && payload.PositionState != "BUY" && payload.PositionState != "SELL" {
		http.Error(w, "position_state must be BUY or SELL", http.StatusBadRequest)
		return
	}
	hasPositionState := payload.PositionState == "BUY" || payload.PositionState == "SELL"

	fullTicker := payload.Ticker
	ticker := payload.Ticker
	exchangePrefix := "ASX:"
	if colonIdx := strings.Index(ticker, ":"); colonIdx != -1 {
		exchangePrefix = ticker[:colonIdx+1]
		ticker = ticker[colonIdx+1:]
	}
	ticker = strings.ToUpper(strings.TrimSpace(ticker))
	if ticker == "" {
		http.Error(w, "ticker is required", http.StatusBadRequest)
		return
	}

	tx, err := db.Begin()
	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	defer tx.Rollback()

	if _, err = tx.Exec(`
		INSERT INTO active_alerts (ticker, script)
		VALUES (?, ?)
		ON CONFLICT(ticker, script) DO UPDATE SET
			created_at = CURRENT_TIMESTAMP
	`, fullTicker, payload.Script); err != nil {
		log.Printf("[ALERT SETUP] Failed to register %s for %s: %v", payload.Script, fullTicker, err)
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}

	if hasPositionState {
		if _, err = tx.Exec(`
			INSERT INTO security_positions (ticker, position_state, last_updated)
			VALUES (?, ?, CURRENT_TIMESTAMP)
			ON CONFLICT(ticker) DO UPDATE SET
				position_state = excluded.position_state,
				stopped_waiting_reentry = CASE
					WHEN excluded.position_state = 'BUY' THEN 0
					ELSE stopped_waiting_reentry
				END,
				last_updated = CURRENT_TIMESTAMP
		`, ticker, payload.PositionState); err != nil {
			log.Printf("[ALERT SETUP] Failed to initialise position for %s: %v", ticker, err)
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
	}

	if scriptMatches(payload.Script, "etf_tms") {
		if _, err = tx.Exec(`
			INSERT INTO etf_positions (ticker, position_state, allocation_pct, cash_allocated, manual_override, last_updated)
			VALUES (?, ?, 0, 0, 0, CURRENT_TIMESTAMP)
			ON CONFLICT(ticker) DO UPDATE SET
				position_state = excluded.position_state,
				last_updated = CURRENT_TIMESTAMP
		`, ticker, payload.PositionState); err != nil {
			log.Printf("[ALERT SETUP] Failed to upsert ETF position for %s: %v", ticker, err)
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
		if _, err = tx.Exec(`
			INSERT INTO etf_allocations (ticker, allocation_percent, base_weight, tactical_status, last_updated)
			VALUES (?, 0, 0, ?, CURRENT_TIMESTAMP)
			ON CONFLICT(ticker) DO UPDATE SET
				tactical_status = excluded.tactical_status,
				last_updated = CURRENT_TIMESTAMP
		`, ticker, payload.PositionState); err != nil {
			log.Printf("[ALERT SETUP] Failed to upsert ETF allocation for %s: %v", ticker, err)
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
		if payload.CompanyName != "" {
			var result sql.Result
			if result, err = tx.Exec(`
				UPDATE stock_analysis
				SET security_type = 'ETF', updated_at = CURRENT_TIMESTAMP
				WHERE name = ?
				   OR UPPER(CASE
						WHEN instr(COALESCE(ticker, ''), ':') > 0 THEN substr(ticker, instr(ticker, ':') + 1)
						ELSE COALESCE(ticker, '')
					END) = ?
			`, payload.CompanyName, ticker); err != nil {
				log.Printf("[ALERT SETUP] Failed to mark %s as ETF security type: %v", ticker, err)
				http.Error(w, err.Error(), http.StatusInternalServerError)
				return
			}
			rowsAffected, _ := result.RowsAffected()
			if rowsAffected == 0 {
				if _, err = tx.Exec(`
					INSERT INTO stock_analysis (ticker, name, security_type, updated_at)
					VALUES (?, ?, 'ETF', CURRENT_TIMESTAMP)
					ON CONFLICT(ticker, name) DO UPDATE SET
						security_type = 'ETF',
						updated_at = CURRENT_TIMESTAMP
				`, fullTicker, payload.CompanyName); err != nil {
					log.Printf("[ALERT SETUP] Failed to create ETF analysis row for %s (%s): %v", ticker, payload.CompanyName, err)
					http.Error(w, err.Error(), http.StatusInternalServerError)
					return
				}
			}
		} else {
			if _, err = tx.Exec(`
				UPDATE stock_analysis
				SET security_type = 'ETF', updated_at = CURRENT_TIMESTAMP
				WHERE UPPER(CASE
					WHEN instr(COALESCE(ticker, ''), ':') > 0 THEN substr(ticker, instr(ticker, ':') + 1)
					ELSE COALESCE(ticker, '')
				END) = ?
			`, ticker); err != nil {
				log.Printf("[ALERT SETUP] Failed to mark %s as ETF security type: %v", ticker, err)
			}
		}
		if _, err = tx.Exec(`
			UPDATE etf_allocations
			SET tactical_status = ?, last_updated = CURRENT_TIMESTAMP
			WHERE ticker = ?
		`, payload.PositionState, ticker); err != nil {
			log.Printf("[ALERT SETUP] Failed to sync ETF tactical status for %s: %v", ticker, err)
		}
	}

	if payload.AnalystPriceTarget != nil && *payload.AnalystPriceTarget > 0 && payload.CompanyName != "" {
		if _, err = tx.Exec(`
			INSERT INTO stock_analysis (ticker, name, analyst_pt, updated_at)
			VALUES (?, ?, ?, CURRENT_TIMESTAMP)
			ON CONFLICT(ticker, name) DO UPDATE SET
				analyst_pt = excluded.analyst_pt,
				updated_at = CURRENT_TIMESTAMP
		`, ticker, payload.CompanyName, *payload.AnalystPriceTarget); err != nil {
			log.Printf("[ALERT SETUP] Failed to update analyst PT for %s (%s): %v", ticker, payload.CompanyName, err)
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
	}

	if err = tx.Commit(); err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}

	log.Printf("[ALERT SETUP] Initialised %s for %s as %s", payload.Script, fullTicker, payload.PositionState)
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"message":         "Alert setup initialised",
		"ticker":          fullTicker,
		"position_ticker": ticker,
		"script":          payload.Script,
		"position_state":  payload.PositionState,
		"exchange_prefix": exchangePrefix,
	})
}

func removeActiveAlert(w http.ResponseWriter, r *http.Request) {
	var payload struct {
		ID     int64  `json:"id"`
		Ticker string `json:"ticker"`
		Script string `json:"script"`
	}

	if err := json.NewDecoder(r.Body).Decode(&payload); err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}

	fullTicker := strings.TrimSpace(payload.Ticker)
	script := normalizeAlertScript(payload.Script)
	if payload.ID > 0 {
		result, err := db.Exec(`DELETE FROM active_alerts WHERE id = ?`, payload.ID)
		if err != nil {
			log.Printf("[ALERT SETUP] Failed to remove active alert id %d: %v", payload.ID, err)
			http.Error(w, err.Error(), http.StatusInternalServerError)
			return
		}
		removed, _ := result.RowsAffected()
		log.Printf("[ALERT SETUP] Removed %d active alert(s) by id %d", removed, payload.ID)
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(map[string]interface{}{
			"message": "Active alert removed",
			"id":      payload.ID,
			"removed": removed,
		})
		return
	}
	if fullTicker == "" || script == "" {
		http.Error(w, "ticker and script are required", http.StatusBadRequest)
		return
	}

	symbol := strings.ToUpper(fullTicker)
	if colonIdx := strings.LastIndex(symbol, ":"); colonIdx != -1 {
		symbol = symbol[colonIdx+1:]
	}
	symbol = strings.TrimSpace(symbol)
	if symbol == "" {
		http.Error(w, "ticker is required", http.StatusBadRequest)
		return
	}

	var result sql.Result
	var err error
	for attempt := 0; attempt < 4; attempt++ {
		result, err = db.Exec(`
			DELETE FROM active_alerts
			WHERE script = ?
			  AND (
				ticker = ?
				OR UPPER(CASE
					WHEN instr(ticker, ':') > 0 THEN substr(ticker, instr(ticker, ':') + 1)
					ELSE ticker
				END) = ?
			  )
		`, script, fullTicker, symbol)
		if err == nil || !strings.Contains(strings.ToLower(err.Error()), "database is locked") {
			break
		}
		time.Sleep(time.Duration(attempt+1) * 250 * time.Millisecond)
	}
	if err != nil {
		log.Printf("[ALERT SETUP] Failed to remove %s for %s: %v", script, fullTicker, err)
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}

	removed, _ := result.RowsAffected()
	log.Printf("[ALERT SETUP] Removed %d active alert(s) for %s (%s)", removed, fullTicker, script)

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"message": "Active alert removed",
		"ticker":  fullTicker,
		"script":  script,
		"removed": removed,
	})
}

// getUnmappedAlerts returns alerts that need manual ticker/company mapping
func getUnmappedAlerts(w http.ResponseWriter, r *http.Request) {
	rows, err := db.Query(`
		SELECT id, ticker, exchange_prefix, alert_type, strength, created_at
		FROM alerts
		WHERE needs_mapping = 1 AND is_active = 1
			AND alert_type NOT IN ('CONNECTED', 'CONNECTION', 'TEST')
			AND ticker NOT IN ('TEST', 'PING', 'CONNECTION')
		ORDER BY created_at DESC
	`)
	if err != nil {
		log.Printf("[API] Failed to query unmapped alerts: %v", err)
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	defer rows.Close()

	type UnmappedAlert struct {
		ID             int       `json:"id"`
		Ticker         string    `json:"ticker"`
		ExchangePrefix string    `json:"exchange_prefix"`
		AlertType      string    `json:"alert_type"`
		Strength       *string   `json:"strength"`
		CreatedAt      time.Time `json:"created_at"`
	}

	var alerts []UnmappedAlert
	for rows.Next() {
		var alert UnmappedAlert
		if err := rows.Scan(&alert.ID, &alert.Ticker, &alert.ExchangePrefix, &alert.AlertType, &alert.Strength, &alert.CreatedAt); err != nil {
			log.Printf("[API] Failed to scan unmapped alert: %v", err)
			continue
		}
		alert.AlertType = canonicalAlertType(alert.AlertType)
		alerts = append(alerts, alert)
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(alerts)
}

// resolveAlertMapping creates a company mapping and optionally adds to watchlist
func resolveAlertMapping(w http.ResponseWriter, r *http.Request) {
	vars := mux.Vars(r)
	alertID := vars["id"]

	var payload struct {
		CompanyName    string `json:"company_name"`
		Ticker         string `json:"ticker"`
		ExchangePrefix string `json:"exchange_prefix"`
		TemplateID     string `json:"template_id"`
		AddToWatchlist bool   `json:"add_to_watchlist"`
		AssetClass     string `json:"asset_class"`
	}

	if err := json.NewDecoder(r.Body).Decode(&payload); err != nil {
		http.Error(w, "Invalid JSON", http.StatusBadRequest)
		return
	}

	if payload.CompanyName == "" || payload.Ticker == "" {
		http.Error(w, "company_name and ticker are required", http.StatusBadRequest)
		return
	}

	if strings.TrimSpace(payload.ExchangePrefix) == "" {
		http.Error(w, "exchange_prefix is required", http.StatusBadRequest)
		return
	}

	// Create company mapping
	_, err := db.Exec(`
		INSERT INTO company_mappings (company_name, ticker, exchange_prefix, template_id)
		VALUES (?, ?, ?, NULLIF(?, ''))
		ON CONFLICT(company_name) DO UPDATE SET
			ticker = excluded.ticker,
			exchange_prefix = excluded.exchange_prefix,
			template_id = COALESCE(NULLIF(excluded.template_id, ''), company_mappings.template_id),
			enriched_at = CURRENT_TIMESTAMP
	`, payload.CompanyName, payload.Ticker, payload.ExchangePrefix, payload.TemplateID)
	if err != nil {
		log.Printf("[API] Failed to create company mapping: %v", err)
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}

	// Mark alert as resolved (no longer needs mapping)
	_, err = db.Exec(`
		UPDATE alerts SET needs_mapping = 0 WHERE id = ?
	`, alertID)
	if err != nil {
		log.Printf("[API] Failed to update alert: %v", err)
	}

	// Optionally add to watchlist (stock_analysis table)
	if payload.AddToWatchlist {
		watchlistTicker := fullTickerForStorage(payload.ExchangePrefix, payload.Ticker)
		if watchlistTicker == "" {
			watchlistTicker = strings.ToUpper(strings.TrimSpace(payload.Ticker))
		}
		// Remove any placeholder entry where name == ticker (created before mapping was known)
		_, err = db.Exec(`
			DELETE FROM stock_analysis WHERE ticker = ? AND name = ?
		`, watchlistTicker, watchlistTicker)
		if err != nil {
			log.Printf("[API] Failed to clean up placeholder stock_analysis for %s: %v", watchlistTicker, err)
		}

		tx, txErr := db.Begin()
		if txErr != nil {
			log.Printf("[API] Failed to begin watchlist upsert: %v", txErr)
		} else {
			if err = setStockAnalysisWatchlistStateTx(tx, watchlistTicker, "", payload.CompanyName, true); err != nil {
				tx.Rollback()
				log.Printf("[API] Failed to add to watchlist: %v", err)
			} else if err = tx.Commit(); err != nil {
				log.Printf("[API] Failed to commit watchlist upsert: %v", err)
			}
		}

		// Also create a security position in BUY state
		_, err = db.Exec(`
			INSERT INTO security_positions (ticker, position_state)
			VALUES (?, 'BUY')
			ON CONFLICT(ticker) DO NOTHING
		`, payload.Ticker)
		if err != nil {
			log.Printf("[API] Failed to create security position: %v", err)
		}

		// Persist primary asset class directly on the analysis row.
		if payload.AssetClass != "" {
			if normalizedClass, ok := resolvePortfolioAssignmentClass(payload.AssetClass); ok {
				var classValue interface{}
				if normalizedClass != "" {
					classValue = normalizedClass
				}
				_, err = db.Exec(`
					UPDATE stock_analysis
					SET primary_asset_class = ?, updated_at = CURRENT_TIMESTAMP
					WHERE ticker = ?
				`, classValue, payload.Ticker)
				if err != nil {
					log.Printf("[API] Failed to persist primary asset class: %v", err)
				} else {
					stampAssetClassSourceByTicker(payload.Ticker, AssetClassSourceSignal)
				}
			} else {
				log.Printf("[API] Ignoring non-conforming primary asset class %q for %s", payload.AssetClass, payload.Ticker)
			}
		}
	}

	log.Printf("[MAPPING] Resolved %s → %s%s (watchlist: %v)", payload.CompanyName, payload.ExchangePrefix, payload.Ticker, payload.AddToWatchlist)

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]interface{}{
		"status":  "success",
		"message": fmt.Sprintf("Mapped %s to %s%s", payload.CompanyName, payload.ExchangePrefix, payload.Ticker),
	})
}
