func resolveExpiredAlerts() {
	result, err := db.Exec(`
		UPDATE alerts
		SET is_active = 0,
		    resolved_at = CURRENT_TIMESTAMP,
		    resolved_reason = 'EXPIRED',
		    resolved_note = 'Signal expired without user action'
		WHERE is_active = 1
		  AND expiry_date IS NOT NULL
		  AND UPPER(TRIM(alert_type)) != 'SELL'
		  AND datetime(expiry_date) < datetime('now')
	`)
	if err != nil {
		log.Printf("[ALPHA EDGE] Failed to resolve expired alerts: %v", err)
		return
	}
	if rows, err := result.RowsAffected(); err == nil && rows > 0 {
		if _, actionErr := db.Exec(`
				UPDATE security_actions
			SET status = 'EXPIRED', updated_at = CURRENT_TIMESTAMP
			WHERE alert_id IN (
				SELECT id FROM alerts WHERE resolved_reason = 'EXPIRED'
			)
			  AND status IN ('OPEN', 'BLOCKED')
			`); actionErr != nil && !securityActionTableMissing(actionErr) {
			log.Printf("[SECURITY ACTIONS] Failed to expire action queue entries: %v", actionErr)
		}
		log.Printf("[ALPHA EDGE] Resolved %d expired alerts", rows)
	}
}

func getAlerts(w http.ResponseWriter, r *http.Request) {
	resolveExpiredAlerts()

	// Check if includeHistory query parameter is set
	includeHistory := r.URL.Query().Get("includeHistory") == "true"

	var rows *sql.Rows
	var err error

	if includeHistory {
		// For history view: Return ALL alerts regardless of status or expiry
		rows, err = db.Query(`
			SELECT a.id, a.ticker, a.alert_type, a.strength, a.expiry_date, a.exchange_prefix, a.timeframe, a.source, a.affected_positions, a.alert_price, a.resolved_reason, a.resolved_note, a.created_at, a.is_active
			FROM alerts a
			ORDER BY a.created_at DESC
		`)
	} else {
		// For the live alert stack: return active alerts that have not expired.
		// Do not hide TradingView events based on our app-side position state.
		// State context belongs in the UI; silently filtering here makes real alerts disappear.
		rows, err = db.Query(`
			SELECT a.id, a.ticker, a.alert_type, a.strength, a.expiry_date, a.exchange_prefix, a.timeframe, a.source, a.affected_positions, a.alert_price, a.resolved_reason, a.resolved_note, a.created_at, a.is_active
			FROM alerts a
			WHERE a.is_active = 1
			AND (
				a.expiry_date IS NULL
				OR datetime(a.expiry_date) >= datetime('now')
			)
			ORDER BY a.created_at DESC
		`)
	}
	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	defer rows.Close()

	alerts := []Alert{}
	for rows.Next() {
		var a Alert
		var ticker, alertType, strength, exchangePrefix sql.NullString
		var expiryDate sql.NullTime
		var timeframe, source, affectedPositions, resolvedReason, resolvedNote sql.NullString
		var alertPrice sql.NullFloat64
		err := rows.Scan(&a.ID, &ticker, &alertType, &strength, &expiryDate, &exchangePrefix, &timeframe, &source, &affectedPositions, &alertPrice, &resolvedReason, &resolvedNote, &a.CreatedAt, &a.IsActive)
		if err != nil {
			log.Printf("[ALPHA EDGE] Failed to scan alert row: %v", err)
			continue
		}
		if ticker.Valid {
			a.Ticker = ticker.String
		}
		if alertType.Valid {
			a.AlertType = alertType.String
		}
		if strength.Valid {
			a.Strength = strength.String
		}
		if expiryDate.Valid {
			value := expiryDate.Time
			a.ExpiryDate = &value
		}
		if exchangePrefix.Valid {
			a.ExchangePrefix = exchangePrefix.String
		}
		a.AlertType = canonicalAlertType(a.AlertType)
		if timeframe.Valid {
			a.Timeframe = timeframe.String
		}
		if source.Valid {
			a.Source = source.String
		}
		if affectedPositions.Valid {
			a.AffectedPositions = affectedPositions.String
		}
		if alertPrice.Valid && alertPrice.Float64 > 0 {
			a.AlertPrice = floatPtr(alertPrice.Float64)
		}
		if resolvedReason.Valid {
			a.ResolvedReason = resolvedReason.String
		}
		if resolvedNote.Valid {
			a.ResolvedNote = resolvedNote.String
		}
		alerts = append(alerts, a)
	}
	rows.Close()

	for i := range alerts {
		attachAlertPriceContext(&alerts[i])
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(alerts)
}

func createAlert(w http.ResponseWriter, r *http.Request) {
	var alert Alert
	if err := json.NewDecoder(r.Body).Decode(&alert); err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}
	alert.AlertType = canonicalAlertType(alert.AlertType)
	if strings.HasPrefix(alert.AlertType, "WEIGHT_") {
		http.Error(w, "Weight reviews are generated by the policy, not manual signals", 400)
		return
	}
	alert.AlertPrice = lookupCurrentMarketPrice(alert.Ticker, alert.ExchangePrefix)

	result, err := db.Exec(`
		INSERT INTO alerts (ticker, alert_type, strength, expiry_date, alert_price)
		VALUES (?, ?, ?, ?, ?)
	`, alert.Ticker, alert.AlertType, alert.Strength, alert.ExpiryDate, nullableFloat(alert.AlertPrice))

	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}

	id, _ := result.LastInsertId()
	alert.ID = int(id)
	alert.CreatedAt = time.Now()
	alert.IsActive = true
	if err := ensureSecurityActionForAlertID(alert.ID); err != nil {
		log.Printf("[SECURITY ACTIONS] Failed to project manual alert %d: %v", alert.ID, err)
	}

	select {
	case alertChannel <- alert:
		log.Printf("[ALPHA EDGE] New alert broadcasted: %s %s", alert.Ticker, alert.AlertType)
	default:
		log.Println("[ALPHA EDGE] Alert channel full, skipping broadcast")
	}

	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(http.StatusCreated)
	json.NewEncoder(w).Encode(alert)
}

func dismissAlert(w http.ResponseWriter, r *http.Request) {
	vars := mux.Vars(r)
	id := vars["id"]
	alertID, parseErr := strconv.Atoi(id)
	if parseErr != nil || alertID < 1 {
		http.Error(w, "Invalid alert id", http.StatusBadRequest)
		return
	}
	if err := ensureSecurityActionForAlertID(alertID); err != nil && err != sql.ErrNoRows {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	if isExit, err := activeExitActionForAlert(alertID); err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	} else if isExit {
		http.Error(w, "Exit actions require execution or an explicit override", http.StatusConflict)
		return
	}

	_, err := db.Exec(`
		UPDATE alerts
		SET is_active = 0,
		    resolved_at = COALESCE(resolved_at, CURRENT_TIMESTAMP),
		    resolved_reason = COALESCE(resolved_reason, 'DISMISSED'),
		    resolved_note = COALESCE(resolved_note, 'Alert dismissed without recording a decision')
		WHERE id = ?
	`, id)

	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}

	log.Printf("[ALPHA EDGE] Alert %s dismissed", id)
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(map[string]string{"status": "dismissed"})
}

func streamAlerts(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "text/event-stream")
	w.Header().Set("Cache-Control", "no-cache")
	w.Header().Set("Connection", "keep-alive")
	// CORS is handled by corsMiddleware (origin allowlist); no wildcard here.

	flusher, ok := w.(http.Flusher)
	if !ok {
		http.Error(w, "Streaming not supported", http.StatusInternalServerError)
		return
	}

	log.Println("[ALPHA EDGE] New SSE client connected")

	// Send initial connection message
	fmt.Fprintf(w, "data: {\"type\":\"connected\"}\n\n")
	flusher.Flush()

	// Listen for new alerts
	sessionCheck := time.NewTicker(15 * time.Second)
	defer sessionCheck.Stop()
	for {
		select {
		case alert := <-alertChannel:
			if ownerAccess.enabled && accessCookie(r, "session") != "" {
				if scope, _, err := ownerSession(r); err != nil || scope != "owner" {
					return
				}
			}
			data, _ := json.Marshal(alert)
			fmt.Fprintf(w, "data: %s\n\n", data)
			flusher.Flush()
		case <-sessionCheck.C:
			if ownerAccess.enabled && accessCookie(r, "session") != "" {
				if scope, _, err := ownerSession(r); err != nil || scope != "owner" {
					return
				}
			}
			fmt.Fprint(w, ": heartbeat\n\n")
			flusher.Flush()
		case <-r.Context().Done():
			log.Println("[ALPHA EDGE] SSE client disconnected")
			return
		}
	}
}

