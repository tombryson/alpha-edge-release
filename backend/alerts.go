func hasActionableStockTMSContext(fullTicker, symbol, companyName string) (bool, string) {
	fullTicker = strings.ToUpper(strings.TrimSpace(fullTicker))
	symbol = canonicalTickerSymbol(symbol)
	if symbol == "" {
		symbol = canonicalTickerSymbol(fullTicker)
	}
	companyName = strings.TrimSpace(companyName)

	var activeHoldings int
	err := db.QueryRow(`
		SELECT COUNT(*)
		FROM holdings h
		WHERE h.is_active = 1
		  AND (
			UPPER(TRIM(COALESCE(h.ticker, ''))) = ?
			OR UPPER(TRIM(COALESCE(h.ticker, ''))) = ?
			OR UPPER(TRIM(COALESCE(h.exchange_prefix, '') || COALESCE(h.ticker, ''))) = ?
			OR LOWER(TRIM(COALESCE(h.company_name, ''))) = LOWER(TRIM(?))
		  )
	`, fullTicker, symbol, fullTicker, companyName).Scan(&activeHoldings)
	if err != nil {
		log.Printf("[TMS] Failed to check active holdings for %s/%s (%s): %v", fullTicker, symbol, companyName, err)
	} else if activeHoldings > 0 {
		return true, "active holding"
	}

	var externalRows int
	err = db.QueryRow(`
		SELECT COUNT(*)
		FROM stock_analysis sa
		WHERE COALESCE(sa.is_external, 0) = 1
		  AND (
			UPPER(TRIM(COALESCE(sa.ticker, ''))) = ?
			OR UPPER(CASE
				WHEN instr(COALESCE(sa.ticker, ''), ':') > 0 THEN substr(sa.ticker, instr(sa.ticker, ':') + 1)
				ELSE COALESCE(sa.ticker, '')
			END) = ?
			OR LOWER(TRIM(COALESCE(sa.name, ''))) = LOWER(TRIM(?))
		  )
	`, fullTicker, symbol, companyName).Scan(&externalRows)
	if err != nil {
		log.Printf("[TMS] Failed to check external analysis rows for %s/%s (%s): %v", fullTicker, symbol, companyName, err)
	} else if externalRows > 0 {
		return true, "external held position"
	}

	var watchlistRows int
	err = db.QueryRow(`
		SELECT COUNT(*)
		FROM stock_analysis sa
		WHERE COALESCE(sa.is_watchlist, 0) = 1
		  AND COALESCE(sa.is_external, 0) = 0
		  AND (
			UPPER(TRIM(COALESCE(sa.ticker, ''))) = ?
			OR UPPER(CASE
				WHEN instr(COALESCE(sa.ticker, ''), ':') > 0 THEN substr(sa.ticker, instr(sa.ticker, ':') + 1)
				ELSE COALESCE(sa.ticker, '')
			END) = ?
			OR LOWER(TRIM(COALESCE(sa.name, ''))) = LOWER(TRIM(?))
		  )
	`, fullTicker, symbol, companyName).Scan(&watchlistRows)
	if err != nil {
		log.Printf("[TMS] Failed to check watchlist rows for %s/%s (%s): %v", fullTicker, symbol, companyName, err)
	} else if watchlistRows > 0 {
		return false, "watchlist-only"
	}

	return false, "not active holding or external position"
}

